// @ts-nocheck: a Bun build script (node:fs, Bun, import.meta.dir), outside the browser tsconfig; the audio test imports it.
// Regenerates src/ui/audio/worker-src.ts: the synthesis worker (src/ui/audio/worker.ts and the pure recipes it imports)
// bundled and minified into one string, which the engine starts as a Blob worker. Run after changing recipes, synth,
// music or jobs:  bun run tools/audio-worker.ts   (audio.test.ts fails while the string is stale).
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const ROOT = resolve(import.meta.dir, '..');
export async function workerSource(): Promise<string> {
  const r = await Bun.build({ entrypoints: [resolve(ROOT, 'src/ui/audio/worker.ts')], minify: true, target: 'browser', format: 'iife' });
  if (!r.success) { for (const l of r.logs) console.error(l); throw new Error('worker build failed'); }
  return (await r.outputs[0].text()).trim();
}
export function workerModule(src: string, names: readonly string[]): string {
  return `// GENERATED by tools/audio-worker.ts from src/ui/audio/worker.ts — do not edit. The synthesis worker as a string,\n` +
    `// started as a Blob worker by ./synthq.ts (no separate file to serve, nothing for the page build to know about), and\n` +
    `// run in a stand-in scope on the main thread where no worker can be made: the recipes ship once (M4 perf pass).\n` +
    `export const WORKER_SRC = ${JSON.stringify(src)};\n` +
    `/** The world recipes' names (recipes.ts WORLD_RECIPES), so the engine can ask whether one exists without the recipes. */\n` +
    `export const WORLD_NAMES: readonly string[] = ${JSON.stringify(names)};\n`;
}
/** The world recipes' names, as the generated module lists them. */
export async function worldNames(): Promise<readonly string[]> {
  return (await import('../src/ui/audio/recipes.ts')).WORLD_RECIPES;
}
if (import.meta.main) {
  const src = await workerSource();
  writeFileSync(resolve(ROOT, 'src/ui/audio/worker-src.ts'), workerModule(src, await worldNames()));
  console.log(`src/ui/audio/worker-src.ts ${(src.length / 1024).toFixed(1)} KB`);
}
