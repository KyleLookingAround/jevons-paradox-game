/**
 * Save format version. M2 CHANGE: 3.
 * Migration rule (implemented in ModelApi.deserialize; versions chain: 1 → 2 → 3):
 *   - version > SAVE_VERSION → null (a save from the future is refused).
 *   - version 2 → 3, then stamped 3. Every field M2 adds that a fresh state supplies is filled by the deep merge
 *     below; the rules here are the ones a merge cannot get right. Applied to a JSON copy, in this order:
 *       1. GameState: pendingDividends [], commons { levels: {}, fund: 0 }, events [], lastOffline null,
 *          charterOffer [] (but see step 6).
 *       2. Every SectorState (open or closed): clearYears 0; settled null; settledBefore false; dividends [];
 *          decadesLean = an array of `false` as long as decadesWithin (M1 decades were judged at the full target, so
 *          none is lean); windowLean false; peakPressure = pressure.
 *          Every AppState: peakAdoption 0.
 *       3. Every BudgetState: pace = the id of the FIRST resolved pace of its sector (see SteadyParams.paces);
 *          w0 = −1 and p0 = −1 as markers, replaced in step 7; clearAt absent; heldAt kept.
 *       4. RunStats: leanDecades 0, decisions 0, decisionsByDecade [], automated 0, automatedByDecade [], opening [],
 *          firstBudgetAt null.
 *       5. MetaState: charter null; orders = the default OrdersState (see OrdersState); runs = [lastRun] if
 *          meta.lastRun exists (its new optional fields stay absent), else []; opening and firstOpening absent;
 *          eventSeq 0; knowhowPeak = a copy of meta.knowhow; peakPopulationEver = max(1, state.peakPopulation).
 *       6. After the state is built: if Derived.freshRun holds and meta.reckonings ≥ 1, charterOffer = the offer
 *          reckon() would draw for this state (see GameState.charterOffer); else [].
 *       7. After the state is built: every budget with the w0/p0 markers gets w0 = Derived.wellbeing of the loaded
 *          state and p0 = that sector's current pressure (the "day drawn" becomes the day loaded).
 *     The v2 field GlobalParams.offlineCapSeconds is content, not save data: nothing to migrate.
 *   - version 1 (or missing) → migrated to version 2 as follows, then to version 3 as above:
 *       top-level `eras` → `sectors` (same keys: the v1 ids 'steam' … 'code' are kept as sector ids); every
 *         `history[i].eras` → `history[i].sectors`; every `news[i].era` → `news[i].sector`;
 *         meta.lastRun.eras → .sectors and .causeEra → .causeSector;
 *       meta.steadyEras → meta.steadySectors; run.steadyEras → run.steadySectors;
 *       meta.furthestEra (an index n) → meta.sectorsOpened = { s: true } for the first n ids of content.sectorOrder;
 *       meta.institutions: `true` → level 1;
 *       meta.slots = max(content.global.startingSlots ?? 2, number of owned institutions);
 *       meta.loadout = every owned institution id still in content, in content order (v1 players are grandfathered:
 *         everything they owned stays seated);
 *       meta.backfiredSectors = { s: true } for every sector whose current-run state has backfired true;
 *       every SectorState: etaAtBase kept if present (the v1 model stored it as an extra), else baseD / baseR, else
 *         baseEta; serviceDelivered 0; decadesWithin []; steadyYears 0; budget null, EXCEPT that a sector with an
 *         active cap lever whose ref > 0 gets budget = { r0: ref, since: state.time, drawnYear: current calendar year };
 *       steadyYearsAll 0; run.decoupledYears 0 (the v1 trend-based definitions do not carry over);
 *       run.wellbeingYears, run.yearsAtTarget, run.budgetDecades 0; run.firstBackfires {};
 *       lever levels clamped to the lever's maxLevel; recycle left unset (default applies);
 *       meta.lastRun's new optional fields stay absent.
 *   - At every version: sectors in the save but not in content are dropped; sectors in content but not in the save are
 *     rebuilt closed; ids of upgrades, levers, Know-how, Institutions, Commons projects, dividends and Charters no
 *     longer in content are dropped (a meta.charter or pending dividend naming an unknown id is cleared or removed;
 *     orders keep only known sector, lever and project ids).
 *   - Any missing field of a version-3 save is rebuilt from a fresh state (deep merge), as in v1. Map- and array-valued
 *     fields the merge cannot type-check (levels, events, pendingDividends, runs, opening, settled) are validated
 *     element by element and invalid entries dropped.
 * The UI may keep its localStorage key; deserialize does the migration.
 */
export const SAVE_VERSION = 3;

