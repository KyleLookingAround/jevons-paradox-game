/**
 * REBOUND — shared contract (M2, "Restraint has a game; run 2 is different"; M1 "v1, honest" underneath).
 *
 * This file is the single source of truth between the workstreams:
 *   - src/core/      pure simulation core (implements ModelApi, no DOM); module map in src/core/README.md;
 *                    public entry src/core/index.ts (`model`)
 *   - src/content/   data for sectors, ages, applications, upgrades, levers, Commons, Charters… (src/content/index.ts
 *                    exports `content: Content`); module map in src/content/README.md
 *   - src/ui/        DOM interface (reads Derived, GameState and the views, calls ModelApi); the world scene engine is
 *                    src/ui/scene/ (its only reader of this contract is src/ui/scene/adapter.ts)
 *
 * Do not edit this file from a workstream. If the contract is wrong or missing something,
 * work around it locally and report it in your final message.
 *
 * Words
 *   - SECTOR (code) = one service + resource economy with its applications, efficiency path, pressure and levers.
 *     It opens at some point in a run and keeps running beside the others. ON SCREEN a sector is an "Industry"
 *     (plural "Industries"). No player-facing text says "sector" or "era" for this unit.
 *   - AGE (code and screen) = a period of the calendar: a year span, the page theme, and the sectors that belong to it.
 *     An age will later own a prestige layer (Reckoning / Treaty / Long Now); nothing here designs that yet.
 *   - v1 called both of these "era". The full old → new mapping is in design/m1-contract-notes.md.
 *
 * Conventions
 *   - All rates are per real second of play. `dt` is in seconds.
 *   - "Model years" = seconds × YEARS_PER_SECOND. Every timer, streak, decade and budget runs on model years.
 *     The *calendar* year shown to the player (Derived.year) is a separate, cosmetic quantity (see AgeDef.yearSpan).
 *   - ModelApi functions are PURE: never mutate the state passed in, always return a new state.
 *     No Date.now(), no Math.random() (use state.seed with a small deterministic PRNG if needed).
 *   - Money is "£" in every sector for simplicity.
 *   - Optional content fields state their default. Search for "M1 CHANGE" for semantics that differ from v1, "M2 CHANGE"
 *     for semantics that differ from M1, and "M2:" for what M2 adds. design/m2-contract-notes.md gives the reasons.
 *   - Nothing in the contract assumes a number of sectors or ages: iterate content.sectorOrder and content.ages.
 *   - "Model decade" = 10 model years of run time (200 s); decade k of a run covers run time × YEARS_PER_SECOND in
 *     [10k, 10k + 10).
 *
 * Forward compatibility (see design/roadmap.md): per-sector run state (budget, levers, settlement) lives in
 * SectorState / LeverState so that M5 can hold one copy per region; meta-level choices (loadout, slots, orders, the
 * Charter) live in MetaState. The unions below (EffectDef, StatKey, LeverRecycle, HeadlineKey, EventKind, Actor,
 * OrderId) will grow; code switching on them must have a default branch that ignores unknown members. M2 keeps the
 * shapes later milestones extend: Actor gains 'dispatch' (M3), 'rival' (M5) and 'agent' (M7); OrdersState gains
 * dispatch defaults (M3); SettledState is self-contained so M4's capstone can create settled sectors at run start;
 * RunSummary carries peak adoption and pressure for M3's before-and-after pictures; MetaState.opening seeds M5's
 * rival; decisions per model decade feed shift 3 (M3). Shared stocks and `feeds` (M4) are not here yet.
 */

