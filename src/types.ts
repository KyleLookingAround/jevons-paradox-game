/**
 * Effects. Two families:
 *   - STANDING effects are modifiers in force while their source is held: an upgrade owned this run (× its level), a
 *     know-how node (× its level), a SEATED institution (each owned level's effects once), or a decade reward earned
 *     this run (× decades earned). They are recomputed, never written into state.
 *     M2 sources of standing effects: a dividend chosen this run (× times chosen), a Commons project (× its level), the
 *     Charter in force (once), a settled sector's settle.dividend (once, while settled), and an institutionLoan (the
 *     loaned levels, once).
 *   - ONE-OFF effects ('mandateAdd', 'capitalAdd', 'slotAdd') fire once at the moment they are granted: an upgrade
 *     level bought, a know-how level bought, a decade completed, a sector's first Steady State. They are ignored on
 *     institutions (an institution is re-applied every run). 'reserveAdd', 'startCapitalMul' and 'startLever' are
 *     standing but act on the state at specific moments, as described per variant.
 *     M2 moments: a dividend chosen, a Commons level bought, a sector's first settlement in a run. They are ignored on
 *     Charters. M2 CHANGE: a know-how level's one-offs fire only the first time that level is ever owned
 *     (MetaState.knowhowPeak), so a respec and re-buy grants nothing twice.
 * Unknown effect types are ignored.
 */
