export type CmpOp = '<' | '<=' | '>' | '>=';

/**
 * Statistics a Cond can read. Scope:
 *   - Global (sector/app ignored): 'time' (run seconds), 'year' (calendar, Derived.year), 'wellbeing', 'population',
 *     'capital', 'mandate', 'reckonings' (meta.reckonings), 'steadyYearsAll', 'clicks' (run.clicks).
 *   - Sector (`sector` required; if the sector is absent from content, closed, or the value is null, the leaf is
 *     FALSE): 'etaFold', 'rFold', 'frontierFold', 'peakRFold' (SectorState.peakR / baseR), 'rebound',
 *     'resourceUse' (R), 'demand' (D), 'servicePrice' (p_s), 'serviceDelivered', 'reserveFraction', 'pressureFraction',
 *     'crises' (SectorState.crisesFired), 'steadyYears', 'budgetDecades' (decadesWithin.length),
 *     'withinBudget' (1 or 0), 'appsFounded' (count of founded applications).
 *   - Application (`app` required, sector inferred from the app; FALSE if that sector is closed):
 *     'adoption', 'appDemand' (AppDerived.demand).
 *   - M2, global: 'decisions' (run.decisions), 'automated' (run.automated), 'commonsLevels' (Σ GameState.commons.levels),
 *     'sectorsSettled' (open sectors with SectorState.settled ≠ null), 'leanDecades' (run.leanDecades),
 *     'fullDecades' (run.budgetDecades − run.leanDecades).
 *   - M2, sector: 'settled' (1 or 0), 'clear' (SectorDerived.clear, 1 or 0), 'clearYears' (SectorState.clearYears),
 *     'leanDecades' and 'fullDecades' with `sector` set (that sector's, this run); global without `sector`.
 * Every value is the one Derived/SectorDerived/AppDerived would report for the same state.
 */
export type StatKey =
  | 'time' | 'year' | 'wellbeing' | 'population' | 'capital' | 'mandate' | 'reckonings' | 'steadyYearsAll' | 'clicks'
  | 'etaFold' | 'rFold' | 'frontierFold' | 'peakRFold' | 'rebound' | 'resourceUse' | 'demand' | 'servicePrice'
  | 'serviceDelivered' | 'reserveFraction' | 'pressureFraction' | 'crises' | 'steadyYears' | 'budgetDecades'
  | 'withinBudget' | 'appsFounded'
  | 'adoption' | 'appDemand'
  /* --- M2 --- */
  | 'decisions' | 'automated' | 'commonsLevels' | 'sectorsSettled' | 'leanDecades' | 'fullDecades'
  | 'settled' | 'clear' | 'clearYears';

/**
 * A data-only condition, evaluated by the core against a state (and the flows it derives).
 *   - { stat, op, value }: compare a statistic (see StatKey for scope rules).
 *   - { owns: id }: id is looked up across all content (ids are unique game-wide) and is true when:
 *       upgrade level ≥ 1 this run · application founded this run · lever level ≥ 1 · institution level ≥ 1 (owned,
 *       seated or not; a Charter's institutionLoan does not count) · know-how level ≥ 1 · achievement earned ·
 *       M2: Commons project level ≥ 1 this run · Charter in force this run (meta.charter === id) · dividend chosen this
 *       run (id in any SectorState.dividends) · a sector id: opened in any run (meta.sectorsOpened). Unknown id → false
 *       (the content lint catches it).
 *   - M2: sector-scoped stat leaves on a SETTLED sector read the values SectorDerived reports for it (see SettledState).
 *   - { flag }: state.flags[flag] === true ('revealed', 'won'; unknown flag → false).
 *   - all / any / not: logical combinators. Empty `all` is true, empty `any` is false.
 * `label` is the player-facing wording of this node ("Own the Separate condenser"), used by checklists
 * (Derived.nextSector). Content should label every direct child of an unlock's top-level `all`.
 * Unknown leaf shapes evaluate false.
 */
export type Cond = (
  | { stat: StatKey; sector?: SectorId; app?: string; op: CmpOp; value: number }
  | { owns: string }
  | { flag: string }
  | { all: Cond[] }
  | { any: Cond[] }
  | { not: Cond }
) & { label?: string };

