  visibleBelow: number;
  foundCost: number;
  /**
   * Steam's twist: each unit of this application's demand adds this much to BOTH reserve and reserveMax per second.
   * Balance rule: keep reserveGainPerService × η × (this app's share of sector demand) < 1 at every reachable η, or the
   * app regenerates more coal than the sector burns and the reserve can never run out.
   */
  reserveGainPerService?: number;
