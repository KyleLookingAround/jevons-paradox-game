export interface ModelApi {
  /**
   * Fresh run. Pass the previous meta to carry Hindsight, know-how, institutions and the loadout over.
   * sectorOrder[0] opens at t = 0 with its free applications founded and its baseline recorded; seated institutions
   * and know-how apply (start capital, start reserves, start levers, reveal). A fresh meta has slots = startingSlots ?? 2.
   * M2: the Charter in meta.charter applies like a seated institution (startFounded applications founded, loans in
   * force); events [] and charterOffer [] (reckon() fills both for its run); pendingDividends [], commons
   * { levels: {}, fund: 0 }, lastOffline null. A fresh meta also has charter null, the default OrdersState, runs [],
   * eventSeq 0, knowhowPeak {}, peakPopulationEver 1.
   */
  createState(content: Content, meta?: MetaState, seed?: number): GameState;

  /**
   * Advance by dt seconds. dt is clamped to [0, MAX_TICK_SECONDS]; it is stepped in sub-steps of at most 1 s.
   * Each step (all open sectors, in sectorOrder): η, applications (availability, sufficiency drift, peaks), reserve,
   * pressure and crises, baseline, trend, serviceDelivered, backfire (direct rebound > 1, first time this run:
   * SectorState.backfired, 'backfire' headline and achievement, meta.backfiredSectors and run.firstBackfires if new),
   * budget auto-draw for active caps (after steady.standingDrawYears), decoupling streak (steadyYears += dt × YEARS_PER_SECOND while decoupling, else
   * reset — a reset of a streak holding ≥ 1 decade emits 'budgetBroken'; each time the streak crosses a multiple of
   * decadeYears a decade is recorded: decadesWithin, run.budgetDecades, decade effects, 'decade' headline; crossing
   * STEADY_STATE_YEARS holds the sector's budget line (BudgetState.heldAt) and sets run.steadySectors / meta.steadySectors, achievement 'steadyState', 'steadySector' headline
   * (once per sector per run) and, if the sector is new to meta.steadySectors, firstSteadyEffects); then population,
   * Mandate and lapses, sector unlocks ('sectorOpened', and 'ageBegins' when it is the first open sector of its age,
   * meta.sectorsOpened), steadyYearsAll and the win, run stats (wellbeingYears, yearsAtTarget, decoupledYears,
   * peakWellbeing), achievements with `when`. Built-in achievements: 'backfire' (above); 'jevonsWasRight' (every
   * efficiency upgrade of a sector that is not excluded by a fork owned, and peakR / baseR ≥ 10); 'degrowthByAccident'
   * (population < 0.6 × peak, some open sector with trendR < 0, wellbeing < target); 'steadyState' (above);
   * 'firstReckoning' (in reckon). Returns the same reference while a Reckoning is pending.
   *
   * M2 CHANGES to the step, in order. Every per-sector rule reads the state and flows at the START of the step, as M1's
   * decoupling does, so the step agrees with what Derived reported for that state.
   *   - Settled sectors skip the per-sector rules above except: openFor += dt (η is recomputed only on unsettle);
   *     resourceUsed and serviceDelivered accrue from the frozen R and D. No crisis, collapse, exhaustion, decade or
   *     streak change; their apps are not updated.
   *   - Unsettled sectors also update AppState.peakAdoption (from AppDerived.adoption) and SectorState.peakPressure.
   *   - A budget auto-drawn for an active cap takes the default pace, w0 = Derived.wellbeing, p0 = the pressure, and
   *     emits 'budgetDrawn' by 'default'.
   *   - The decade streak uses SectorDerived.decoupling (wellbeing ≥ decadeWellbeing). On a decoupling step,
   *     windowLean ||= (W < wellbeingTarget) BEFORE the crossing test; at a crossing the decade is recorded with
   *     decadesLean.push(windowLean), run.leanDecades += windowLean ? 1 : 0, then windowLean = false. A decade fires
   *     the sector's decadeEffects (one-offs × the line's pace dividendMul), the 'decade' headline and event, and, if the
   *     sector resolves a non-empty decadeChoices list, appends a PendingDividend (see GameState.pendingDividends). On a
   *     non-decoupling step the decade streak, windowLean and clearYears reset to 0 / false.
   *   - The Steady streak: clearYears += dy while SectorDerived.sinkHeld, else 0. The first step on a line with
   *     SectorDerived.clear true sets BudgetState.clearAt and emits 'clearSkies' (headline and event). Steady State
   *     (M2 CHANGE: was the decade streak crossing STEADY_STATE_YEARS) is clearYears crossing STEADY_STATE_YEARS, with
   *     every M1 consequence listed above (heldAt, run/meta.steadySectors, achievement, headline, firstSteadyEffects)
   *     and the 'steadyState' event.
   *   - Mandate: upkeep = lever upkeep + Σ settlement defences; the lapse rule is extended as in SettledState.
   *   - Commons fund: commons.fund += fundShare × (levy revenue routed to 'commons') × dt.
   *   - A sector opening in the step founds any of its applications named by a standing startFounded effect.
   *   - steadyYearsAll: as GameState.steadyYearsAll (M2 CHANGE).
   *   - meta.peakPopulationEver = max(itself, population).
   *   - Every headline the step emits whose HeadlineKey has an EventKind of the same meaning also emits that event
   *     (see EventKind), in the same order ('steadySector' → 'steadyState', 'steadyAll' → 'won').
   *   - Last, if the step is an order tick, the standing orders run (see OrdersState).
   */
  tick(state: GameState, content: Content, dt: number): GameState;
  /**
   * Offline catch-up: steps of at most 5 s, capped at Derived.offlineCapSeconds (M2 CHANGE: was offlineCapSeconds).
   * M2: it never ends a run unseen. With holdBefore = GlobalParams.offline.holdBefore (default 'collapse'): it checks
   * each step's result before keeping it; if the step fired a crisis in any sector (holdBefore 'crisis'), or made a
   * Reckoning pending by collapse or exhaustion (holdBefore 'crisis' or 'collapse'), it DISCARDS that step and stops,
   * returning the state one step before. The remaining time is forfeited (banked time is a later milestone). The held
   * crisis or collapse then happens in live play, seconds after the player returns; a further fastForward from a held
   * state holds again at once (simulated 0), so the board waits for the player. Standing orders run inside the steps
   * exactly as in tick. The returned state carries lastOffline (see OfflineReport), also when it simulated 0 seconds.
   * M2 (offline fix): two rules apply only inside fastForward: Hindsight accrues at GlobalParams.offline.hindsightRate
   * (RunStats.hindsightWithheld), and a full pendingDividends list forgoes new offers instead of overflowing (see
   * GameState.pendingDividends). Both are deterministic and leave tick() untouched.
   * A call with seconds ≤ 0 (after clamping; NaN counts as 0) returns the same reference and writes nothing. If a
   * Reckoning is already pending it simulates nothing (heldBy 'pending').
   */
  fastForward(state: GameState, content: Content, seconds: number): GameState;

  derive(state: GameState, content: Content): Derived;

  /* --- player actions: each returns the new state, or the same reference if the action is not allowed --- */
  /* M2: every in-run action below that changes the state counts once in run.decisions / decisionsByDecade (see
   *     RunStats.decisions) and emits its events with by 'player'. Every in-run action except setOrders (and reckon
   *     itself) is refused while a Reckoning is pending. */
  /** capital += Derived.clickValue; run.clicks++. */
  click(state: GameState, content: Content): GameState;
  /** Refused if not visible, maxed, excluded, unaffordable, or a Reckoning is pending. One-off effects fire.
   *  M2: refused in a settled sector (its upgrades are not visible); recorded in run.opening ('upgrade', 'player');
   *  events 'upgradeBought', then 'stageReached' if SectorDerived.stage rose. */
  buyUpgrade(state: GameState, content: Content, upgradeId: string): GameState;
  /** M2: refused in a settled sector; recorded in run.opening ('found', 'player'); event 'appFounded'. */
  foundApp(state: GameState, content: Content, appId: string): GameState;
  /**
   * Raise or lower a lever to `level` (0 … maxLevel). Raising charges Mandate (levels at or below an institution's
   * startLever level are free); lowering is free and immediate. Raising a lever from 0 snapshots duty's ref; raising any
   * lever (M1 balance: from any level) draws the sector's budget at the current R if it has none.
   * M2: the line it draws takes the default pace, w0 = Derived.wellbeing and p0 = the sector's pressure, and sets
   * run.firstBudgetAt if null. Refused for a settled sector's levers. Event 'leverEnacted' on raises.
   */
  setLever(state: GameState, content: Content, leverId: string, level: number): GameState;
  /** M1: choose where a duty or cap lever's revenue goes. Refused for options the lever does not offer. Free.
   *  M2: 'commons' is refused until the Commons are open; refused when the option is already in force. */
  setLeverRecycle(state: GameState, content: Content, leverId: string, option: LeverRecycle): GameState;
  /**
   * M1: draw (or redraw) the sector's budget line at its current R. Requires flags.revealed, the sector open with R > 0,
   * and no pending Reckoning. Redrawing resets the sector's streak; earned decades are kept. Free. Emits 'budgetDrawn'.
   * M2: `pace` is a pace id of the sector's resolved paces (default: the first; an unknown id is refused). Records w0,
   * p0 and the pace; a redraw also resets clearYears and windowLean. Refused for a settled sector. Sets
   * run.firstBudgetAt if null.
   */
  drawBudget(state: GameState, content: Content, sector: SectorId, pace?: string): GameState;
  /**
   * M2: resolve the OLDEST pending dividend of `sector` with option 0 or 1: removes it from pendingDividends, appends
   * the chosen id to SectorState.dividends, fires its one-offs (mandateAdd and capitalAdd × its mul), emits
   * 'dividendChosen'. Refused if the sector has no pending dividend, the option is not 0 or 1, or a Reckoning is pending.
   */
  chooseDecadeDividend(state: GameState, content: Content, sector: SectorId, option: number): GameState;
  /**
   * M2: settle the sector. Allowed when the sector is open and not settled, SectorDef.settle exists, flags.revealed,
   * no Reckoning is pending, and the sector is AT Steady State now: clearYears ≥ STEADY_STATE_YEARS and
   * SectorDerived.sinkHeld. Effect: SectorState.settled = a SettledState snapshot of the sector's current flows (D, R,
   * ps, pPre, income, pressure, η, defect, N, spillMul, extraD, per-app demand and adoption); every lever of the sector
   * goes to level 0 (ref 0; their upkeep stops; their recycle choice is kept); settle.dividend's standing effects come
   * into force, and its one-offs fire if settledBefore was false (then settledBefore = true); 'settled' headline and
   * event. The budget line, decades and dividends are kept; the Market and the Civil Service skip the sector.
   */
  settle(state: GameState, content: Content, sector: SectorId): GameState;
  /**
   * M2: end the settlement (also what the lapse rule does when a defence cannot be paid, with by 'default'). Effect:
   * settled = null; the sector resumes from its frozen state (reserve, pressure and apps as they were; η recomputed for
   * today's openFor, so an autoEta sector resumes with the gains of the settled years; levers stay at 0); steadyYears,
   * clearYears and windowLean reset (Steady State must be earned again before settling again; the line keeps its
   * heldAt); settle.dividend stops. 'unsettled' headline and event. Free; refused if not settled or a Reckoning is
   * pending. The cost is what is lost: the dividend, the levers, the streak, and whatever the economy has grown into.
   */
  unsettle(state: GameState, content: Content, sector: SectorId): GameState;
  /**
   * M2: buy the next level of a Commons project whose CommonsView reports canBuy. The capital cost is taken from
   * commons.fund first, then from capital; the Mandate cost from Mandate. One-off effects fire. 'commonsBuilt' headline
   * and event.
   */
  buyCommons(state: GameState, content: Content, id: string): GameState;
  /**
   * M2: change standing orders (MetaState.orders) with a partial patch. paybackMax is clamped to [1, 86400] and
   * keepSeconds to [0, 86400]; non-finite numbers, unknown sector ids, lever ids not of that sector and unknown project
   * ids are dropped. Settings of an order that is not available are stored but inert. Returns the same reference if
   * nothing changes. Counts as a decision unless Derived.freshRun. Allowed at any time, also while a Reckoning is pending.
   */
  setOrders(state: GameState, content: Content, patch: OrdersPatch): GameState;
  /** End the run. Uses the pending cause if there is one, else 'chosen'. Returns the fresh next run.
   *  M2: see hindsightOnReckon for everything it records. */
  reckon(state: GameState, content: Content): GameState;
  /**
   * M1 CHANGE: allowed only while Derived.freshRun (between runs). Buys the next level of a node whose KnowhowView
   * reports canBuy. One-off effects (slotAdd) fire. The fresh run is rebuilt from the new meta (createState with the
   * same seed), keeping its news, Mandate, clicks and any capital earned by clicking.
   * M2: one-offs fire only if the new level exceeds meta.knowhowPeak[id], which is then raised. Every between-runs
   * rebuild (this, buyInstitution, setLoadout, chooseCharter, respecKnowhow) also keeps events, charterOffer and
   * lastOffline.
   */
  buyKnowhow(state: GameState, content: Content, id: string): GameState;
  /** M1 CHANGE: buys the next level (level 1 unlocks). Allowed only while Derived.freshRun; rebuilds the run as buyKnowhow. */
  buyInstitution(state: GameState, content: Content, id: string): GameState;
  /**
   * M1: replace the loadout. Allowed only while Derived.freshRun. Refused unless every id is owned, ids are distinct,
   * and Σ slots ≤ meta.slots. Rebuilds the run as buyKnowhow.
   */
  setLoadout(state: GameState, content: Content, ids: string[]): GameState;
  /**
   * M2: choose this run's Charter from Derived.charterOffer (or null to have none). Allowed only while
   * Derived.freshRun; refused for an id not in the offer, or if it is already the one in force. Sets meta.charter,
   * rebuilds the run as buyKnowhow, then adds the 'charter' headline and a 'charterChosen' event (neither for null).
   */
  chooseCharter(state: GameState, content: Content, id: string | null): GameState;
  /**
   * M2: Know-how respec. Allowed only while Derived.freshRun. Every know-how node (of `tree` only, if given; a node's
   * tree is KnowhowDef.tree ?? 'general') goes to level 0, and meta.hindsight += respecRefund × Σ over the removed
   * levels l = 0 … level − 1 of cost × costGrowth^l (the price list, not what was paid). Branch exclusions of the cleared
   * nodes lift. One-off effects are neither reversed nor granted again (knowhowPeak is kept). A node of tier ≥ 2 left
   * without a tier − 1 node in its tree keeps its level (tiers gate buying, not owning). Refused if nothing in scope is
   * owned. Rebuilds the run as buyKnowhow. Not a decision.
   */
  respecKnowhow(state: GameState, content: Content, tree?: string): GameState;

  /* --- views for the UI --- */
  /** Called about once a second and after each action; runs projections (the core caches them).
   *  M2: projections never run standing orders. */
  /** With `sector`, only that sector's eligible cards are projected; every card is still returned, the others with
   *  `projectedDecade: null` and `bringsWithinReach: []`. Without it, every eligible card is projected. Projections are
   *  cached on the state's structure and a 20 s time bucket, so a projected line may lag the exact one by up to a bucket. */
  upgradeViews(state: GameState, content: Content, sector?: SectorId): UpgradeView[];
  leverViews(state: GameState, content: Content): LeverView[];
  /** M1: the Hindsight shop, Know-how half (content order). */
  knowhowViews(state: GameState, content: Content): KnowhowView[];
  /** M1: the Hindsight shop, Institutions half, and the loadout (content order). */
  institutionViews(state: GameState, content: Content): InstitutionView[];
  /** M2: the Commons panel (content order; invisible projects included with visible false). */
  commonsViews(state: GameState, content: Content): CommonsView[];
  /**
   * M2: the calendar year (fractional) at run time `time` of the current run: the AgeDef.yearSpan formula evaluated
   * with each sector's openFor replaced by openFor − (state.time − time), a sector counting as open at `time` when that
   * is ≥ 0 (sectorOrder[0] is open from 0). For time = state.time it equals Derived.year. Times after state.time
   * extrapolate with the sectors open now; negative times are treated as 0. Used for "held since 1840" and the ledger.
   */
  yearAt(state: GameState, content: Content, time: number): number;
  /**
   * M1 CHANGE: Hindsight a Reckoning now would pay: HindsightTerms.total (see GlobalParams.hindsight). Reckoning adds
   * it to meta.hindsight and hindsightEarned, fills meta.lastRun (with hindsightTerms), reckonings++, grants
   * 'firstReckoning', and returns createState(content, newMeta, nextSeed) with a 'reckoning' headline.
   * M2: reckon() also builds the RunSummary with its M2 fields and appends it to meta.runs (trimmed to RUN_HISTORY_MAX;
   * lastRun = that summary); writes meta.opening (and meta.firstOpening if absent) from run.opening, run.firstBudgetAt,
   * the run's length and its Charter; sets meta.charter = null; then, on the new run, draws charterOffer (see
   * GameState.charterOffer) and emits the 'reckoning' event. Pending dividends, the Commons and settlements end with
   * the run; meta.orders carries over.
   */
  hindsightOnReckon(state: GameState, content: Content): number;

  /* --- persistence --- */
  serialize(state: GameState): string;
  /** Returns null if the string is not a usable save. Migrates older versions (see SAVE_VERSION). */
  deserialize(text: string, content: Content): GameState | null;
}
