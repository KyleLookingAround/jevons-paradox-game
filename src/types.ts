export type LeverKind =
  /** Tax that holds the service price up as η rises. With strength s (0–0.999) and p the price before duty
   *  (pre-levy price + permit part):  dutyPart = s × max(0, p_ref − p), p_ref = p when the lever first went above 0
   *  (LeverState.ref). The strongest duty lever of a sector applies. Revenue = dutyPart × D (never player income). */
  | 'duty'
  /** M1 CHANGE: hard ceiling capR = value × budgetR(t) — a fraction of the sector's declining BUDGET LINE, not of
   *  "R when enacted". The tightest cap of a sector applies. If the sector has no budget when a cap is active, one is
   *  drawn at the current R on the first step with demand once the sector has been open steady.standingDrawYears
   *  (M1 balance; default 0); until then the cap has no line and does nothing. A permit price is added to p_r until R meets the cap.
   *  Leak: when permit > value2 × p_r (leakAbove), the effective cap rises by up to 25%:
   *    leak = 0.25 × clamp(permit / (leakAbove × p_r) − 1, 0, 1), solved self-consistently; value2 absent = no leak.
   *  Squeeze limit: a cap never squeezes out more than 95% of the demand above the floors (lock-in floors and drawsOn
   *  demand, which no price removes): effective target = max(capR × (1 + leak), R_floor + 0.05 × (R_free − R_floor)),
   *  R_free = R with no cap. Below that the cap is simply not met. Permit revenue = permit × R (never player income). */
  | 'cap'
  /** Saturation of the sector's applications drifts toward `value` × S_i at rate value2 per second (default 0.01):
   *  satMul −= (satMul − target) × (1 − exp(−rate × dt)). Relaxed, it recovers toward 1 at 0.01 per second. */
  | 'sufficiency'
  /** A share σ = min(value, value2 / D) of the service comes from a renewable flow: uses no resource, makes no
   *  pressure, costs 1.5 × c per unit (blended into the pre-levy price). value2 = flowCap in service units per second
   *  (absent = unlimited). Several substitution levers in one sector: shares add (≤ 1), flowCaps add. */
  | 'substitution'
  /** A share of resource used returns to the reserve ('stock' only): drain = R × (1 − share). Shares add, ≤ 0.95. */
  | 'circularity'
  /** Cuts this sector's indirect spill by a share. Shares add, ≤ 1. */
  | 'greenSpending'
  /** Code: spends `value` share of effective capacity (≤ 0.9) to shrink P at value2 (default 1) per unit capacity per second. */
  | 'deletion'
