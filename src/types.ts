export interface Content {
  /** M1 CHANGE (was `eras`): every sector, keyed by id. */
  sectors: Record<SectorId, SectorDef>;
  /**
   * M1: the order sectors are listed, iterated and (by default) unlocked in. Contains every key of `sectors` exactly
   * once. sectorOrder[0] is open at the start of every run.
   */
  sectorOrder: SectorId[];
  /** M1: the ages, in calendar order. Every sector belongs to exactly one age (AgeDef.sectors). */
  ages: AgeDef[];
  upgrades: UpgradeDef[];
  levers: LeverDef[];
  knowhow: KnowhowDef[];
  institutions: InstitutionDef[];
  achievements: AchievementDef[];
  /**
   * Broadsheet headline variants keyed by event (the fallback set). Placeholders substituted by the model:
   * `{sector}` sector name (on screen an industry), `{age}` age name, `{app}` application name, `{resource}`,
   * `{service}`, `{year}` calendar year (integer), `{n}` an event count (the decade number for 'decade', the crisis
   * number for 'crisis', else empty). M2: `{name}` the name of the Commons project ('commonsBuilt') or Charter
   * ('charter'), kept as authored (a proper name), else empty. Variant choice is deterministic from state.seed, time and the news count.
   * M1 balance: substitution is case-aware. `{app}`, `{resource}` and `{service}` are common nouns: away from the start
   * of a sentence their first letter is lower-cased ("demand for coal"), unless the name starts with an acronym ("AI
   * models") — only the first letter is touched, so later proper nouns survive. `{age}` lower-cases a leading "The"
   * mid-sentence ("Welcome to the Coal Age"). `{sector}` is the proper name of an industry and is kept as authored.
   * A sentence starts at the beginning of the template or after . ! or ? and a space (opening quotes allowed).
   * Content should therefore author those names in sentence case with any proper noun after the first word.
   */
  headlines: Record<HeadlineKey, string[]>;
  /**
   * M1: sector-specific variants. When an event belongs to a sector and `sectorHeadlines[sector][key]` is a non-empty
   * array, it is used instead of `headlines[key]`. Default: absent (everything falls back to `headlines`).
   */
  sectorHeadlines?: Record<SectorId, Partial<Record<HeadlineKey, string[]>>>;
  global: GlobalParams;
  /* --- M2 --- */
  /**
   * M2: every decade dividend, flat (ids unique game-wide). Pairs of ids are offered per decade (SteadyParams
   * .decadeChoices). Default: [] (no choices; decades pay only their decadeEffects, as in M1).
   */
  dividends?: DividendDef[];
  /** M2: the Commons projects, in display order. Default: [] (no Commons). */
  commons?: CommonsDef[];
  /** M2: the Charters, in content order (the order the deterministic draw indexes; see GameState.charterOffer). Default: []. */
  charters?: CharterDef[];
  /**
   * M2: display names of Know-how trees (KnowhowDef.tree), keyed by tree id. Default for a missing tree: the UI shows
   * the tree id with its first letter capitalised. Content should name every tree it uses (the lint checks).
   */
  knowhowTrees?: Record<string, { name: string; blurb?: string }>;
  /**
   * M2: player-facing wording of the recycle options (button name and one-line explanation). A lever may override the
   * blurb (LeverDef.recycleBlurb). Default for a missing option: name = the option id capitalised, blurb ''.
   * LeverView.recycleChoices carries the resolved wording; the UI does not resolve it itself.
   */
  recycleText?: Partial<Record<LeverRecycle, { name: string; blurb: string }>>;
  /* --- M3 (all optional; absent = the M2 game) --- */
  /** M3: the recurring cast who write to the proprietor (CastDef). Default []. */
  cast?: CastDef[];
  /** M3: every dispatch, flat (ids unique game-wide; content order is the tie-break order of the draw). Default []. */
  dispatches?: DispatchDef[];
  /** M3: ambient headline templates (AmbientDef). Default []. */
  ambient?: AmbientDef[];
  /** M3: the Histories, in display order (HistoryDef). Default []. */
  histories?: HistoryDef[];
  /** M3: Archive notes (ArchiveDef), in display order. Default []. */
  archive?: ArchiveDef[];
  /** M3: the Proprietor's Day texts: the pamphlet and the return templates (ProprietorText). Default: absent (the
   *  core falls back to a one-line headline "Household survey published" and an empty body). */
  proprietor?: ProprietorText;
  /** M3: the first ending's credits and retrospective templates (EndingText). Default: absent (the UI shows a plain
   *  "Steady State" card with the core's retrospective items untitled). */
  ending?: EndingText;
}

/**
 * M1: a period of the calendar. The page theme belongs to the age; a sector adds only an accent.
 * Later an age may own a prestige layer (a field such as `layer` will be added then); nothing depends on that now.
 */
export interface AgeDef {
  id: AgeId;
  /** On screen: "The Coal Age", "The Great Acceleration"… */
  name: string;
  /** One line shown when the age begins. */
  tagline: string;
  /**
   * Calendar span [first, last]. last may be Infinity. Calendar of the age while any of its sectors is open:
   *   y = max( yearSpan[0] + T × YEARS_PER_SECOND,  max over its open sectors s of (s.firstYear ?? yearSpan[0]) + s.openFor × YEARS_PER_SECOND )
   *   with T = the largest openFor among its open sectors (time since the age began);
   *   if y > yearSpan[1]: y = yearSpan[1] + (y − yearSpan[1]) × CALENDAR_LATE_RATE.
   * Derived.year = max over ages with an open sector (so it never runs backwards when something opens).
   */
  yearSpan: [number, number];
  /**
   * Page theme key; the UI keeps a registry of looks. M1 looks: 'ledger', 'gaslight', 'chrome', 'terminal', 'agentic'.
   * Unknown keys fall back to the UI's default look.
   */
  theme: string;
  /** Sector ids that belong to (and can open in) this age, in display order. */
  sectors: SectorId[];
}

