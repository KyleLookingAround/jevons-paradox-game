/**
 * M2: standing orders, automation as policy (MetaState.orders: they persist across Reckonings as the player's settings;
 * a fresh meta has the default below). They run inside the step (so tick and fastForward run them alike) at ORDER
 * TICKS: a step from t0 to t1 is an order tick when floor(t1 × YEARS_PER_SECOND / intervalYears) >
 * floor(t0 × YEARS_PER_SECOND / intervalYears) (intervalYears = GlobalParams.orders.intervalYears ?? 1). They act on
 * the state the step has just produced, after everything else in the step, in this order: Market, Civil Service,
 * Treasury rules. They never run in projections (UpgradeView), while a Reckoning is pending, or while the run is fresh.
 * When no order is active the step pays one comparison. Results with different step lengths (tick's 1 s against
 * fastForward's 5 s) differ only as much as the step itself does: same rules, same boundaries.
 * An order is ACTIVE when available, `on`, and (Market) its sector switch is on.
 *   Available: Market — meta.reckonings ≥ GlobalParams.orders.marketFromReckoning (default 1) or a standing
 *   orderUnlock 'market'; Civil Service and Treasury rules — a standing orderUnlock effect for them is in force.
 *
 * THE MARKET (default on). At each order tick, for each open, unsettled sector in sectorOrder whose switch is on
 * (sectors[s] !== false), it takes AT MOST ONE action, the candidate with the shortest payback:
 *   candidates: (a) every available, unfounded application with foundCost ≤ capital; (b) every upgrade of the sector
 *     with kind 'efficiency' or 'capital' that is visible, not maxed, not excluded, has NO `excludes` (forks are the
 *     player's), and costs ≤ capital. Never 'research' or 'prospect' cards; never levers, budgets or Commons.
 *   payback(a) = cost(a) / gain(a), infinite if the gain is ≤ 0, where (M2 BALANCE) the gain is what the action pays
 *     per second as a mill owner reckons it: the running cost it saves at today's output plus any rise in income,
 *       gain(a) = Σ over open unsettled sectors of D_now × max(0, pPre_now − pPre_after) + max(0, income_after − income_now)
 *     (pPre = resource price / η + capital cost per unit of service, before levies; income = Derived.incomePerSec),
 *     each "after" computed by solving the state with that one action applied (no time passes). An engine is sold on
 *     the coal it saves (Boulton & Watt's royalty was a third of it); an application on the income it brings. So the
 *     Market buys efficiency even while demand is price-inelastic and the card lowers income: the saving is passed on
 *     in the price, and the use grows to meet it.
 *   it acts if the shortest payback ≤ paybackMax; ties: applications before upgrades, then content order.
 *   The action is the same state change as foundApp / buyUpgrade (capital charged, one-offs, headlines), recorded with
 *   by 'market': in run.opening (if room), events ('appFounded' / 'upgradeBought', and 'stageReached'), run.automated
 *   and automatedByDecade; never in run.decisions. Later sectors in the same tick see the capital it spent.
 * THE CIVIL SERVICE (default off; levers chosen per sector). At each order tick, for each open, unsettled sector in
 *   sectorOrder with a budget line and a non-empty `levers` list: if R > budgetR × (1 + BUDGET_TOLERANCE), it raises
 *   ONE level of the listed lever (of that sector, visible, below maxLevel) with the lowest next-level Mandate cost that
 *   Mandate covers (ties: list order), as setLever would ('leverEnacted' by 'civilService'); else, if
 *   W < SectorDerived.decadeWellbeing and R ≤ 0.9 × budgetR, it lowers ONE level of the listed lever with the highest
 *   net upkeep (ties: list order). Each counts once in run.automated.
 * TREASURY RULES (default off). At each order tick, if the Commons are open: the first project in `projects` that a
 *   buyCommons call would accept with capital reduced by keepSeconds × Derived.incomePerSec (the fund is not reduced)
 *   gets one level ('commonsBuilt' by 'treasury', run.automated += 1).
 * Default OrdersState: { market: { on: true, paybackMax: GlobalParams.orders.marketPaybackMax ?? 120, sectors: {} },
 *   civilService: { on: false, levers: {} }, treasury: { on: false, keepSeconds: 60, projects: [] } }.
 */
export interface OrdersState {
  market: {
    on: boolean;
    /** Seconds. */
    paybackMax: number;
    /** Per-sector switch; a missing key means ON (so a newly opened sector starts with the Market on). */
    sectors: Record<SectorId, boolean>;
  };
  civilService: {
    on: boolean;
    /** Lever ids the Civil Service may move, per sector (ids of other sectors' levers are ignored). */
    levers: Record<SectorId, string[]>;
  };
  treasury: {
    on: boolean;
    /** Capital kept back, in seconds of income. */
    keepSeconds: number;
    /** Commons project ids in priority order. */
    projects: string[];
  };
}

